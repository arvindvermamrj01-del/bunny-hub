-- BunnyHub: separate social-style Posts storage.
-- Run in the SAME Supabase project used by SUPABASE_URL in Cloudflare Pages.
-- Posts are private drafts by default and are not part of vh_content / Movie Catalog.

create table if not exists public.vh_posts (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 180),
  description text not null default '',
  category text not null default '',
  post_type text not null check (post_type in ('video','song','photo')),
  status text not null default 'draft' check (status in ('draft','published','archived')),
  visibility text not null default 'private' check (visibility in ('private','public')),
  storage_provider text not null check (storage_provider in ('backblaze_b2','cloudflare_r2')),
  storage_path text not null,
  thumbnail_path text,
  file_name text,
  file_size bigint not null check (file_size > 0),
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint vh_posts_draft_private_only check (status <> 'draft' or visibility = 'private')
);

create index if not exists vh_posts_owner_created_idx
  on public.vh_posts (created_by, created_at desc);

alter table public.vh_posts enable row level security;

-- All reads/writes go through authenticated Cloudflare Pages APIs using the
-- server-side service-role key. No public or browser-role access is granted.
revoke all on public.vh_posts from anon, authenticated;
grant all on public.vh_posts to service_role;
grant usage, select on sequence public.vh_posts_id_seq to service_role;

comment on table public.vh_posts is
  'Separate private social posts workspace; not the Movie Catalog. Drafts are private by default.';
