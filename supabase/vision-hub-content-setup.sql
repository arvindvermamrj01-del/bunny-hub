-- Media uploaded here must be owned by you or licensed for public display.
-- Profiles are required for user sessions and admin-role checks.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  fullname text,
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

-- Bring an existing profiles table up to the columns this site expects.
alter table public.profiles add column if not exists fullname text;
alter table public.profiles add column if not exists role text not null default 'user';
alter table public.profiles add column if not exists created_at timestamptz not null default now();
alter table public.profiles enable row level security;

-- Backfill profiles for accounts that already exist.
insert into public.profiles (id, fullname, role)
select id,
       coalesce(raw_user_meta_data ->> 'full_name', raw_user_meta_data ->> 'fullname'),
       'user'
from auth.users
on conflict (id) do nothing;

-- Create a user profile automatically whenever a new account signs up.
create or replace function public.handle_new_BUNNY_HUB_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, fullname, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'fullname'),
    'user'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_BUNNY_HUB on auth.users;
create trigger on_auth_user_created_BUNNY_HUB
after insert on auth.users
for each row execute function public.handle_new_BUNNY_HUB_user();

drop policy if exists "Users can read own profile" on public.profiles;
create policy "Users can read own profile" on public.profiles
  for select to authenticated using (id = auth.uid());

drop policy if exists "Users can insert own user profile" on public.profiles;
create policy "Users can insert own user profile" on public.profiles
  for insert to authenticated with check (id = auth.uid() and role = 'user');

