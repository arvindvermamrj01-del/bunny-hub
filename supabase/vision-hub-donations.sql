-- BunnyHub donations: UPI confirmations are pending until an administrator verifies them.
-- This records user-submitted references; it does NOT claim automatic payment verification.
begin;

create table if not exists public.vh_donations (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  donor_name text not null check (char_length(btrim(donor_name)) between 1 and 80),
  amount numeric(10,2) not null check (amount >= 1 and amount <= 999),
  currency text not null default 'INR' check (currency = 'INR'),
  payment_reference text not null check (payment_reference ~ '^[A-Za-z0-9-]{8,64}$'),
  status text not null default 'pending' check (status in ('pending','verified','rejected')),
  admin_note text,
  created_at timestamptz not null default now(),
  verified_at timestamptz,
  verified_by uuid references auth.users(id) on delete set null
);

create unique index if not exists vh_donations_reference_unique
  on public.vh_donations (lower(payment_reference));
create index if not exists vh_donations_created_at_idx
  on public.vh_donations (created_at desc);
create index if not exists vh_donations_user_id_idx
  on public.vh_donations (user_id);

alter table public.vh_donations enable row level security;
revoke all on public.vh_donations from anon, authenticated;
grant insert on public.vh_donations to anon, authenticated;
grant select, update on public.vh_donations to authenticated;
grant usage, select on sequence public.vh_donations_id_seq to anon, authenticated;

drop policy if exists "vh_donations_public_submit" on public.vh_donations;
create policy "vh_donations_public_submit" on public.vh_donations
  for insert to anon, authenticated
  with check (
    status = 'pending'
    and verified_at is null
    and verified_by is null
    and (user_id is null or user_id = (select auth.uid()))
  );

drop policy if exists "vh_donations_owner_or_admin_read" on public.vh_donations;
create policy "vh_donations_owner_or_admin_read" on public.vh_donations
  for select to authenticated
  using (
    user_id = (select auth.uid())
    or exists (
      select 1 from public.profiles p
      where p.id = (select auth.uid()) and p.role = 'admin'
    )
  );

drop policy if exists "vh_donations_admin_update" on public.vh_donations;
create policy "vh_donations_admin_update" on public.vh_donations
  for update to authenticated
  using (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin'))
  with check (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin'));

commit;
