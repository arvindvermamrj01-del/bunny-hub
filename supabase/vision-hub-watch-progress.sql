-- Resume playback / continue watching progress.
create table if not exists public.vh_watch_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  content_id text not null,
  position_seconds double precision not null default 0 check (position_seconds >= 0),
  duration_seconds double precision not null default 0 check (duration_seconds >= 0),
  updated_at timestamptz not null default now(),
  unique(user_id, content_id)
);
create index if not exists vh_watch_progress_user_updated_idx
  on public.vh_watch_progress(user_id, updated_at desc);
alter table public.vh_watch_progress enable row level security;
drop policy if exists "Users manage their own watch progress" on public.vh_watch_progress;
create policy "Users manage their own watch progress"
  on public.vh_watch_progress for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());
