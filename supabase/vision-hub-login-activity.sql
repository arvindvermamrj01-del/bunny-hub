-- BunnyHub: main-admin-only sign-in history.
-- Additive, minimal data (account ID and timestamp only); no IP address or user-agent.
-- Apply once in Supabase SQL Editor after confirming the project's backup.
begin;

create table if not exists public.vh_login_activity (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists vh_login_activity_created_at_idx
  on public.vh_login_activity (created_at desc);

alter table public.vh_login_activity enable row level security;

drop policy if exists "vh_login_activity_insert_own" on public.vh_login_activity;
create policy "vh_login_activity_insert_own" on public.vh_login_activity
  for insert to authenticated
  with check (user_id = (select auth.uid()));

drop policy if exists "vh_login_activity_admin_read" on public.vh_login_activity;
create policy "vh_login_activity_admin_read" on public.vh_login_activity
  for select to authenticated
  using (public.vh_is_admin());

revoke all on public.vh_login_activity from anon, authenticated;
grant insert, select on public.vh_login_activity to authenticated;
grant usage, select on sequence public.vh_login_activity_id_seq to authenticated;

commit;
