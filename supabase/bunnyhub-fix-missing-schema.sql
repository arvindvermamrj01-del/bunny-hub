-- BunnyHub Missing Schema & RPC Hotfix (Idempotent)
-- Run in Supabase Dashboard > SQL Editor to fix all 400 / 404 frontend errors.

begin;

-- 1) Ensure vh_site_settings has setting_key and setting_value columns
create table if not exists public.vh_site_settings (
  setting_key text primary key,
  setting_value text,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);
alter table public.vh_site_settings add column if not exists setting_key text;
alter table public.vh_site_settings add column if not exists setting_value text;
alter table public.vh_site_settings add column if not exists updated_by uuid;
alter table public.vh_site_settings add column if not exists updated_at timestamptz not null default now();
alter table public.vh_site_settings enable row level security;

drop policy if exists "vh_site_settings_public_read" on public.vh_site_settings;
create policy "vh_site_settings_public_read"
  on public.vh_site_settings for select to anon, authenticated
  using (true);

-- 2) Ensure vh_analytics_events has session_tag column
create table if not exists public.vh_analytics_events (
  id bigint generated by default as identity primary key,
  event_type text not null,
  content_id bigint references public.vh_content(id) on delete set null,
  session_tag text,
  created_at timestamptz not null default now()
);
alter table public.vh_analytics_events add column if not exists session_tag text;
alter table public.vh_analytics_events enable row level security;

-- 3) Ensure private schema and public.vh_get_popular_content(p_limit) RPC exist
create schema if not exists private authorization postgres;
revoke all on schema private from public;
grant usage on schema private to anon, authenticated, service_role;

create or replace function private.vh_get_popular_content(p_limit integer default 10)
returns table(content_id bigint, view_count bigint)
language sql stable security definer set search_path = '' as $$
  select e.content_id, count(*)::bigint
  from public.vh_analytics_events e
  join public.vh_content c on c.id = e.content_id
  where e.event_type = 'content_view'
    and e.content_id is not null
    and e.created_at >= now() - interval '30 days'
    and c.published = true
    and c.content_type <> 'Episode'
  group by e.content_id
  order by count(*) desc, max(e.created_at) desc
  limit greatest(1, least(coalesce(p_limit, 10), 50));
$$;
revoke all on function private.vh_get_popular_content(integer) from public;
grant execute on function private.vh_get_popular_content(integer) to anon, authenticated;

create or replace function public.vh_get_popular_content(p_limit integer default 10)
returns table(content_id bigint, view_count bigint)
language sql stable security invoker set search_path = '' as $$
  select * from private.vh_get_popular_content(p_limit);
$$;
revoke all on function public.vh_get_popular_content(integer) from public;
grant execute on function public.vh_get_popular_content(integer) to anon, authenticated;

-- 4) Reload PostgREST schema cache immediately
notify pgrst, 'reload schema';

commit;
