-- Cross-device watchlist for authenticated BunnyHub users.
create table if not exists public.vh_user_watchlist (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  content_id text not null,
  created_at timestamptz not null default now(),
  unique(user_id, content_id)
);
create index if not exists vh_user_watchlist_user_created_idx
  on public.vh_user_watchlist(user_id, created_at desc);
alter table public.vh_user_watchlist enable row level security;
drop policy if exists "Users manage their own watchlist" on public.vh_user_watchlist;
create policy "Users manage their own watchlist"
  on public.vh_user_watchlist for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());
