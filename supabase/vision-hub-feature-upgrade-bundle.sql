-- ===== supabase/bunnyhub-donations.sql =====
-- BunnyHub donations: UPI confirmations are pending until an administrator verifies them.
-- This records user-submitted references; it does NOT claim automatic payment verification.

create table if not exists public.vh_donations (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  donor_name text not null check (char_length(btrim(donor_name)) between 1 and 80),
  amount numeric(10,2) not null check (amount >= 1 and amount <= 999),
  currency text not null default 'INR' check (currency = 'INR'),
  payment_reference text not null check (payment_reference ~ '^[A-Za-z0-9-]{8,64}$'),
  status text not null default 'pending' check (status in ('pending','verified','rejected')),
  admin_note text,
  created_at timestamptz not null default now(),
  verified_at timestamptz,
  verified_by uuid references auth.users(id) on delete set null
);

create unique index if not exists vh_donations_reference_unique
  on public.vh_donations (lower(payment_reference));
create index if not exists vh_donations_created_at_idx
  on public.vh_donations (created_at desc);
create index if not exists vh_donations_user_id_idx
  on public.vh_donations (user_id);

